import {
	BadRequestException,
	HttpException,
	HttpStatus,
	Injectable,
	NotFoundException,
	ServiceUnavailableException,
} from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { ClassConstructor, plainToInstance } from 'class-transformer';
import { validateSync } from 'class-validator';
import { HotelsInquiry } from '../../libs/dto/hotel/hotel.inquiry';
import { RoomsInquiry } from '../../libs/dto/room/room.inquiry';
import { AvailableRoomsInquiry } from '../../libs/dto/room/room.availability';
import { HotelSort } from '../../libs/enums/hotel.enum';
import { RoomSort } from '../../libs/enums/room.enum';
import { HotelService } from '../hotel/hotel.service';
import { RoomService } from '../room/room.service';
import { ChatbotInput, ChatbotReply, ChatbotSource } from './chatbot.dto';
import { chatbotInstructions, chatbotTools } from './chatbot.tools';

type Part = {
	text?: string;
	thought?: boolean;
	functionCall?: { name: string; args?: Record<string, unknown>; id?: string };
	[key: string]: unknown;
};
type Content = { role: string; parts: Part[] };
@Injectable()
export class ChatbotService {
	private readonly requests = new Map<string, { count: number; until: number }>();
	private active = 0;
	constructor(
		private readonly config: ConfigService,
		private readonly hotels: HotelService,
		private readonly rooms: RoomService,
	) {}

	async ask(input: ChatbotInput, client: string): Promise<ChatbotReply> {
		const apiKey = this.config.get<string>('GEMINI_API_KEY')?.trim();
		if (!apiKey) throw new ServiceUnavailableException('Hotelia assistant is not configured yet.');
		this.limit(client);
		this.active++;
		const abort = new AbortController();
		const timeout = setTimeout(() => abort.abort(), 30000);
		try {
			const contents: Content[] = input.history.map((turn) => ({ role: turn.role, parts: [{ text: turn.text }] }));
			contents.push({ role: 'user', parts: [{ text: input.message.trim() }] });
			const sources = new Map<string, ChatbotSource>();
			for (let round = 0; round < 3; round++) {
				const content = await this.generate(apiKey, contents, abort.signal);
				const calls = content.parts.filter((part) => part.functionCall);
				if (!calls.length) {
					const answer = content.parts
						.filter((part) => !part.thought && typeof part.text === 'string')
						.map((part) => part.text)
						.join('\n')
						.trim();
					if (!answer)
						throw new ServiceUnavailableException('The assistant could not answer. Please rephrase your question.');
					// Account routing is controlled by Hotelia, not generated by the model.
					const safeAnswer = answer.replace(/\/account(?:\?[^\s`<>\)]+)?/g, (url) =>
						[
							'/account',
							...[
								'myProfile',
								'myBookings',
								'myFavorites',
								'recentlyVisited',
								'myArticles',
								'writeArticle',
								'followers',
								'followings',
							].map((category) => `/account?category=${category}`),
						].includes(url)
							? url
							: '/account',
					);
					return { answer: safeAnswer.slice(0, 4000), sources: [...sources.values()] };
				}
				if (calls.length > 3 || round === 2)
					throw new ServiceUnavailableException('Please ask a more specific question.');
				// Preserve model parts including thought signatures required by Gemini tool calls.
				contents.push(content);
				const parts: Part[] = [];
				for (const part of calls) {
					const call = part.functionCall!;
					let result: unknown;
					try {
						result = await this.tool(call.name, call.args ?? {}, sources);
					} catch (error) {
						if (error instanceof BadRequestException || error instanceof NotFoundException)
							result = { error: 'Invalid search details or hotel not found. Ask the user to clarify.' };
						else throw error;
					}
					parts.push({
						functionResponse: { name: call.name, ...(call.id ? { id: call.id } : {}), response: { result } },
					});
				}
				contents.push({ role: 'user', parts });
			}
			throw new ServiceUnavailableException('Please ask a more specific question.');
		} finally {
			clearTimeout(timeout);
			this.active--;
		}
	}

	private limit(client: string) {
		const now = Date.now();
		for (const [key, value] of this.requests) if (value.until <= now) this.requests.delete(key);
		const entry = this.requests.get(client) ?? { count: 0, until: now + 60000 };
		if (entry.count >= 5 || this.active >= 6 || this.requests.size >= 5000)
			throw new HttpException(
				'The assistant is busy. Please wait a minute and try again.',
				HttpStatus.TOO_MANY_REQUESTS,
			);
		entry.count++;
		this.requests.set(client, entry);
	}

	private async generate(key: string, contents: Content[], signal: AbortSignal): Promise<Content> {
		const model = this.config.get<string>('GEMINI_MODEL')?.trim() || 'gemini-3.5-flash-lite';
		if (!/^[a-zA-Z0-9.-]+$/.test(model))
			throw new ServiceUnavailableException('Invalid assistant model configuration.');
		try {
			const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`, {
				method: 'POST',
				signal,
				headers: { 'Content-Type': 'application/json', 'x-goog-api-key': key },
				body: JSON.stringify({
					systemInstruction: {
						parts: [{ text: `${chatbotInstructions}\nToday (UTC): ${new Date().toISOString().slice(0, 10)}.` }],
					},
					contents,
					tools: chatbotTools,
					generationConfig: { maxOutputTokens: 2000, temperature: 0.2 },
				}),
			});
			if (!response.ok)
				throw new ServiceUnavailableException(
					response.status === 429
						? 'Gemini quota reached. Please try again later.'
						: 'The assistant is temporarily unavailable.',
				);
			const body = await response.json();
			const content = body.candidates?.[0]?.content;
			if (!content || !Array.isArray(content.parts))
				throw new ServiceUnavailableException('The assistant could not answer. Please rephrase your question.');
			return { role: 'model', parts: content.parts };
		} catch (error) {
			if (error instanceof ServiceUnavailableException) throw error;
			// Never propagate provider responses, request headers or API keys into GraphQL logs.
			throw new ServiceUnavailableException('The assistant is temporarily unavailable. Please try again.');
		}
	}

	private validated<T extends object>(type: ClassConstructor<T>, input: object): T {
		const value = plainToInstance(type, input);
		if (validateSync(value, { whitelist: true, forbidNonWhitelisted: true }).length)
			throw new BadRequestException('Invalid search details');
		return value;
	}
	private async tool(
		name: string,
		args: Record<string, unknown>,
		sources: Map<string, ChatbotSource>,
	): Promise<unknown> {
		if (name === 'searchHotels') {
			const allowed = [
				'destination',
				'text',
				'minPrice',
				'maxPrice',
				'minRating',
				'checkIn',
				'checkOut',
				'guests',
				'rooms',
			];
			if (Object.keys(args).some((key) => !allowed.includes(key))) throw new BadRequestException('Unsupported filter');
			const input = this.validated(HotelsInquiry, { page: 1, limit: 5, sort: HotelSort.RATING, search: args });
			const result = await this.hotels.getHotels(input);
			return {
				totalMatches: result.metaCounter?.[0]?.total ?? 0,
				hotels: result.list.map((hotel) => {
					const url = `/hotel/detail?hotelId=${hotel._id.toString()}`;
					sources.set(url, { title: hotel.hotelName, url });
					return {
						hotelId: hotel._id.toString(),
						name: hotel.hotelName,
						city: hotel.hotelCity,
						country: hotel.hotelCountry,
						description: hotel.hotelDescription.slice(0, 800),
						amenities: hotel.hotelAmenities,
						rating: hotel.hotelRating,
						startingPriceUSD: hotel.startingPrice ?? null,
						url,
					};
				}),
			};
		}
		if (name === 'hotelRooms' || name === 'availableRooms') {
			// Only hotels obtained from the public catalog during this request can be queried.
			if (typeof args.hotelId !== 'string' || !sources.has(`/hotel/detail?hotelId=${args.hotelId}`))
				throw new BadRequestException('Search for the hotel first');
			const result =
				name === 'hotelRooms'
					? await this.rooms.getRooms(
							this.validated(RoomsInquiry, { ...args, page: 1, limit: 5, sort: RoomSort.PRICE_ASC }),
						)
					: await this.rooms.getAvailableRooms(
							this.validated(AvailableRoomsInquiry, { ...args, page: 1, limit: 5, sort: RoomSort.PRICE_ASC }),
						);
			return {
				hotelId: args.hotelId,
				checkedDates: name === 'availableRooms' ? { checkIn: args.checkIn, checkOut: args.checkOut } : null,
				rooms: result.list.map((room) => ({
					name: room.roomName,
					type: room.roomType,
					pricePerNightUSD: room.roomPrice,
					capacity: room.roomCapacity,
					amenities: room.roomAmenities,
					...('availableQuantity' in room ? { availableQuantity: room.availableQuantity } : {}),
				})),
			};
		}
		throw new BadRequestException('Unsupported assistant tool');
	}
}
